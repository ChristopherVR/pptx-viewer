/**
 * Regression guard: charts loaded from a `.pptx` must have their `chartData`
 * populated during load.
 *
 * The slide loader parses a chart `<p:graphicFrame>` into a `type: 'chart'`
 * element but, until {@link PptxSlideLoaderService.enrichChartData} was added,
 * never populated `element.chartData` (only SmartArt was enriched on load). With
 * `chartData` absent, every binding's chart renderer short-circuits to the
 * neutral "Chart" placeholder, so a real chart never rendered from a file.
 *
 * The fixture is `e2e/fixtures/chart-gallery.pptx` (one chart per slide, 14
 * kinds), authored by `e2e/fixtures/generate-chart-fixture.ts`.
 */
import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { describe, it, expect } from 'vitest';

import { PptxHandler } from '../../core/PptxHandler';

const fixture = fileURLToPath(
	new URL('../../../../../e2e/fixtures/chart-gallery.pptx', import.meta.url),
);

describe('chart enrichment on load', () => {
	it('populates chartData for every chart graphic frame in a loaded deck', async () => {
		// The fixture is generated by the e2e global-setup and committed to the
		// repo; skip defensively if a checkout lacks it rather than failing.
		if (!existsSync(fixture)) {
			return;
		}
		const bytes = readFileSync(fixture);
		const handler = new PptxHandler();
		const data = await handler.load(
			bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength),
		);
		const charts = data.slides.flatMap((s) => s.elements).filter((e) => e.type === 'chart');
		const enriched = charts.filter((c) => c.type === 'chart' && c.chartData);

		expect(charts.length).toBeGreaterThan(0);
		// Every parsed chart element must carry chartData after load.
		expect(enriched).toHaveLength(charts.length);
		// And the parsed data must name a concrete chart type (not an empty stub).
		for (const c of enriched) {
			if (c.type === 'chart') {
				expect(c.chartData?.chartType, `${c.id}: chartType`).toBeTruthy();
			}
		}
	});
});
