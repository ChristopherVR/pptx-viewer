/**
 * Regression guard: OLE objects loaded from a `.pptx` must have their authored
 * preview image resolved into `previewImageData` during load.
 *
 * The slide loader parses an OLE `<p:graphicFrame>` into a `type: 'ole'` element
 * and records the preview picture's relationship as a relative `previewImage`
 * path, but - until preview resolution was added to
 * {@link PptxHandlerRuntimeLoadSession.enrichOleElementsWithEmbeddedData} - never
 * turned that path into the `previewImageData` data-URL every binding's OLE
 * renderer actually reads. Without it, a real OLE object never showed its
 * preview and always fell back to the neutral type-badge placeholder (the same
 * class of gap the chart-enrichment-on-load guard covers for charts).
 *
 * The fixture is `e2e/fixtures/ole-embed.pptx` (one slide, one embedded PDF OLE
 * object with a real preview PNG), authored by
 * `e2e/fixtures/generate-ole-ink-fixtures.ts`.
 */
import { existsSync, readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

import { describe, it, expect } from 'vitest';

import { PptxHandler } from '../../core/PptxHandler';

const fixture = fileURLToPath(
	new URL('../../../../../e2e/fixtures/ole-embed.pptx', import.meta.url),
);

describe('ole enrichment on load', () => {
	it('resolves previewImageData and embedded payload for a loaded OLE object', async () => {
		// The fixture is generated by the e2e global-setup and committed to the
		// repo; skip defensively if a checkout lacks it rather than failing.
		if (!existsSync(fixture)) {
			return;
		}
		const bytes = readFileSync(fixture);
		const handler = new PptxHandler();
		const data = await handler.load(
			bytes.buffer.slice(bytes.byteOffset, bytes.byteOffset + bytes.byteLength),
		);
		const oleElements = data.slides.flatMap((s) => s.elements).filter((e) => e.type === 'ole');

		expect(oleElements.length).toBeGreaterThan(0);
		for (const el of oleElements) {
			if (el.type !== 'ole') {
				continue;
			}
			// The authored preview picture must be decoded to a usable URL the
			// renderer can set as an <img src> (a data: URL, or a blob: object
			// URL depending on the host's image-decoding path).
			expect(el.previewImageData, `${el.id}: previewImageData`).toMatch(/^(data:image\/|blob:)/u);
			// The embedded payload is still recovered for download / open.
			expect(el.oleEmbeddedData, `${el.id}: oleEmbeddedData`).toMatch(/^data:/u);
		}
	});
});
