#!/usr/bin/env node
/**
 * Regenerate `packages/shared/src/render/google-fonts-catalogue.ts` from the
 * Google Fonts metadata feed.
 *
 * The viewer's webfont fallback (`packages/shared/src/render/google-webfonts.ts`)
 * decides which referenced-but-missing families to load from the Google
 * Fonts CSS2 API by looking them up in this bundled catalogue. A bundled list
 * means no per-family network probe: nothing about the deck reaches Google
 * until a family is known to be served, and the browser console stays free
 * of the CORS / 400 errors a probe of an unknown family produces.
 *
 * Run: `bun run fonts:catalogue` (or `node scripts/update-google-fonts-catalogue.mjs`).
 */

import { writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const METADATA_URL = 'https://fonts.google.com/metadata/fonts';
const OUT_PATH = resolve(
	dirname(fileURLToPath(import.meta.url)),
	'../packages/shared/src/render/google-fonts-catalogue.ts',
);

const response = await fetch(METADATA_URL);
if (!response.ok) {
	throw new Error(`${METADATA_URL} answered ${response.status}`);
}
// The feed has historically carried an anti-JSON-hijacking `)]}'` prefix.
const text = (await response.text()).replace(/^\)\]\}'\s*/u, '');
const metadata = JSON.parse(text);
const families = [
	...new Set(
		metadata.familyMetadataList
			.map((entry) => String(entry.family).trim())
			.filter((family) => family.length > 0),
	),
].sort((a, b) => a.localeCompare(b, 'en'));

if (families.length < 1000) {
	throw new Error(`only ${families.length} families in the feed; refusing to shrink the catalogue`);
}

const today = new Date().toISOString().slice(0, 10);
// Single quotes to match the repo's oxfmt style, so the output is already formatted.
const quote = (family) => `'${family.replace(/[\\']/gu, '\\$&')}'`;
const body = families.map((family) => `\t${quote(family)},`).join('\n');
const source = `/**
 * GENERATED by scripts/update-google-fonts-catalogue.mjs on ${today}; do not
 * edit by hand. Every family name the Google Fonts CSS2 API served on that
 * date, in the API's own spelling (family names are matched case-insensitively
 * and requested with this canonical spelling).
 *
 * Refresh with \`bun run fonts:catalogue\` when a deck references a family
 * Google has added since.
 */

/** Date the catalogue was last regenerated (ISO yyyy-mm-dd). */
export const GOOGLE_FONTS_CATALOGUE_DATE = '${today}';

/** Family names served by the Google Fonts CSS2 API, sorted. */
export const GOOGLE_FONTS_FAMILIES: readonly string[] = [
${body}
];
`;

writeFileSync(OUT_PATH, source);
console.log(`Wrote ${families.length} families to ${OUT_PATH}`);
